from langchain.tools import tool

from app.rag.rag_service import RAGService

_rag_service = RAGService()

_EMPTY_RESULT = (
    "知识库中未检索到与该问题相关的政策内容。"
    "请如实告知用户没有找到相关规定，不要凭常识编造政策，也不要臆测补偿或时效。"
)


@tool
def search_knowledge(query: str) -> str:
    """检索企业知识库，获取退款、配送、售后、会员等官方政策与规则的原文片段。

    什么时候应该调用：
    - 用户询问规则与政策本身，例如"退款多久到账"、"运费怎么算"、"能不能七天无理由退货"、
      "会员有哪些权益"、"保修期多久"、"积分怎么用"、"发票怎么开"。
    - 回答这类问题必须依据本工具返回的知识库内容，不得凭模型自身知识编造或推测规则。
    - 政策问题不需要订单号，不要因为用户没给订单号就向用户追问订单号。

    什么时候不要调用：
    - 用户查询的是自己的具体订单或包裹数据（订单状态、金额、商品、是否发货、运单号、到哪了），
      应调用 query_order 或 query_logistics，本工具查不到任何订单数据。
    - 本工具只回答通用政策，不能据此断言某个具体订单的退款进度或物流位置。
    - 用户只是打招呼或与政策无关的闲聊时，不要调用本工具。

    返回值：命中时返回按相关度排序的知识库原文片段，请只依据这些片段作答；
    未命中时返回未检索到提示，此时应如实告知用户，不要编造政策内容。

    Args:
        query: 检索问题，使用完整、具体的自然语言问句，例如"退款到账需要多久"。
    """
    context = _rag_service.search(query)
    if not context:
        return _EMPTY_RESULT
    return f"以下是知识库中与问题相关的内容：\n\n{context}"
